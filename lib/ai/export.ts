/**
 * Numbered Q/A block with locale-free `Q1.`/`A1.` labels; body text stays
 * raw (multi-line answers allowed). A session with turns but no dialogue
 * (or none at all) renders the italic note instead of an empty block.
 */
function qaMarkdownLines(turns: TranscriptTurn[]): string[] {
  const pairs = qaPairsFromTurns(turns)
  if (pairs.length === 0) return ['_No dialogue recorded._']
  const lines: string[] = []
  pairs.forEach((pair, i) => {
    const n = i + 1
    lines.push(`**Q${n}.** ${pair.question}`)
    lines.push(`**A${n}.** ${pair.answer}`)
    lines.push('')
  })
  return lines
}

/**
 * "## Participant Profile" labeled lines; null/empty fields are omitted.
 * Personality axes follow the SLIDER_POLAR_LABELS convention shared with
 * buildActiveRosterSummary: name the pole the value leans toward
 * (>= 50 → the high pole).
 */
function personaProfileLines(persona: Persona): string[] {
  const lines: string[] = [`- Region: ${mdInline(persona.region)}`]
  if (persona.occupation)
    lines.push(`- Occupation: ${mdInline(persona.occupation)}`)
  if (persona.gender) lines.push(`- Gender: ${mdInline(persona.gender)}`)
  if (persona.age !== null) lines.push(`- Age: ${persona.age}`)
  if (persona.incomeBracket)
    lines.push(`- Income Bracket: ${mdInline(persona.incomeBracket)}`)
  if (persona.interviewStance) {
    lines.push(`- Interview Stance: ${mdInline(persona.interviewStance)}`)
  }
  if (persona.backgroundTags.length > 0) {
    lines.push(
      `- Background Tags: ${mdInline(persona.backgroundTags.join(';'))}`,
    )
  }
  for (const key of Object.keys(SLIDER_POLAR_LABELS) as Array<
    keyof typeof SLIDER_POLAR_LABELS
  >) {
    const value: number | undefined = persona.personalitySliders[key]
    if (value === undefined) continue
    const pole = SLIDER_POLAR_LABELS[key][value >= 50 ? 1 : 0]
    lines.push(`- ${key} ${value} — leaning ${pole}`)
  }
  return lines
}

/**
 * Short profile brief for run/session reports: Region + Occupation
 * (Region is NOT NULL in the schema so it always renders), plus Age when
 * `includeAge` (the run participant section wants it, the session brief
 * doesn't).
 */
function personaBriefLines(persona: Persona, includeAge: boolean): string[] {
  const lines: string[] = [`- Region: ${mdInline(persona.region)}`]
  if (persona.occupation)
    lines.push(`- Occupation: ${mdInline(persona.occupation)}`)
  if (includeAge && persona.age !== null) lines.push(`- Age: ${persona.age}`)
  return lines
}

function sessionHeading(transcript: Transcript, ordinal: number): string {
  return `### Session ${ordinal} — ${mdInline(transcript.title?.trim() || 'Untitled')} (${shortIso(transcript.createdAt.toISOString())})`
}

/**
 * Per-persona Markdown report: H1 + exported date + integrity blockquote,
 * Participant Profile, Bio, then one `Session <n>` block per transcript
 * (chronological input order). Provenance (system prompt, model snapshot)
 * is intentionally absent — it belongs to the JSON backup only.
 */
export function buildPersonaExportMarkdown(
  persona: Persona,
  transcripts: Transcript[],
): string {
  const lines: string[] = [
    `# Interview Report — ${mdInline(persona.name)}`,
    '',
    `Exported: ${shortIso(new Date().toISOString())}`,
    '',
    `> ${EXPORT_INTEGRITY_LINE}`,
    '',
    '## Participant Profile',
    '',
    ...personaProfileLines(persona),
  ]
  if (persona.generatedBio?.trim()) {
    lines.push('', '## Bio', '', persona.generatedBio.trim())
  }
  if (transcripts.length > 0) {
    lines.push('', '## Sessions', '')
    transcripts.forEach((transcript, i) => {
      if (i > 0) lines.push('')
      lines.push(
        sessionHeading(transcript, i + 1),
        '',
        ...qaMarkdownLines(transcript.turns),
      )
    })
  }
  return lines.join('\n').trimEnd()
}

export type RunExportItem = {
  item: RunItem
  persona: Persona
  transcript: Transcript | null
}

/**
 * Per-run Markdown report: H1 + integrity blockquote, Overview (research
 * context + N-of-M completion), the numbered interview script, then one
 * participant section per run item. A run holds ONE group transcript per
 * persona — its Q/A renders directly under the participant heading, no
 * Session sub-heading. Items without a completed transcript say so instead
 * of silently rendering an empty participant (error-kind note kept).
 */
export function buildRunExportMarkdown(
  run: Run,
  items: RunExportItem[],
  script: string[],
): string {
  const lines: string[] = [
    `# Interview Report — Run ${shortIso(run.createdAt.toISOString())}`,
    '',
    `> ${EXPORT_INTEGRITY_LINE}`,
    '',
    '## Overview',
    '',
  ]
  if (run.researchContext?.trim()) {
    lines.push(`- Research Context: ${mdInline(run.researchContext)}`)
  }
  const doneCount = items.filter(({item}) => item.status === 'done').length
  lines.push(`- Participants: ${doneCount} of ${items.length} completed`)
  lines.push('', '## Interview Script', '')
  script.forEach((question, i) => {
    lines.push(`${i + 1}. ${mdInline(question)}`)
  })
  lines.push('', '## Participants', '')
  items.forEach(({item, persona, transcript}, i) => {
    if (i > 0) lines.push('')
    lines.push(`### ${mdInline(persona.name)} (${mdInline(item.status)})`, '')
    if (!transcript || item.status !== 'done') {
      // run_items.error holds only a fixed short kind ('timeout',
      // 'persona missing', …): runNextStepAction stores err.kind and
      // never err.message, which can embed the LM Studio endpoint URL.
      // mdInline is defense-in-depth, keeping the note on one line even
      // if a legacy row carried a newline.
      lines.push(
        item.error
          ? `_${mdInline(`No transcript — run item not completed (error: ${item.error}).`)}_`
          : '_No transcript — run item not completed._',
      )
      return
    }
    lines.push(
      ...personaBriefLines(persona, true),
      '',
      ...qaMarkdownLines(transcript.turns),
    )
  })
  return lines.join('\n').trimEnd()
}

/** Per-session Markdown report: H1 + exported date + integrity + brief profile + Q/A. */
export function buildSessionExportMarkdown(
  persona: Persona,
  transcript: Transcript,
): string {
  const lines: string[] = [
    `# Interview Session — ${mdInline(persona.name)}`,
    '',
    `Exported: ${shortIso(new Date().toISOString())}`,
    '',
    `> ${EXPORT_INTEGRITY_LINE}`,
    '',
    ...personaBriefLines(persona, false),
    '',
    ...qaMarkdownLines(transcript.turns),
  ]
  return lines.join('\n').trimEnd()
}

/**
 * Wide comparison matrix for cross-persona analysis: one row per script
 * question (0-based `question_index` + verbatim question — same 0-based
 * convention as the long CSV's `turn_index`), one column per participant in
 * item order. The answer cell reads that persona's transcript turn-pair at
 * the same index — runNextStepAction appends script questions in order, so
 * pair i IS the answer to script question i. Participants without a
 * transcript (or whose transcript is shorter than the script) still get a
 * column; their cells stay empty, never fabricated.
 */
export function buildRunComparisonCsv(
  run: Run,
  items: RunExportItem[],
): string {
  const pairsByItem = items.map(({transcript}) =>
    transcript ? qaPairsFromTurns(transcript.turns) : null,
  )
  const rows: string[][] = [
    ['question_index', 'question', ...items.map(({persona}) => persona.name)],
  ]
  run.questionScript.forEach((question, index) => {
    rows.push([
      String(index),
      question,
      ...pairsByItem.map((pairs) => pairs?.[index]?.answer ?? ''),
    ])
  })
  return rows.map((row) => row.map(csvEscape).join(',')).join('\r\n')
}

