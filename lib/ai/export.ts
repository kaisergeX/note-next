/**
 * Localizable strings for the Markdown report builders. lib/ai/export.ts
 * stays pure (no next-intl import): the API routes resolve the labels via
 * buildReportLabels (lib/ai/report-labels.ts) and pass them in, because
 * routes live outside the [locale] segment and read the locale from the
 * `?locale=` query param.
 */
export type ReportLabels = {
  personaTitle: (name: string) => string
  sessionTitle: (name: string) => string
  runTitle: (stamp: string) => string
  sessionHeading: (n: number, title: string, stamp: string) => string
  exportedLine: (stamp: string) => string
  integrityLine: string
  participantProfile: string
  overview: string
  researchContext: string
  interviewScript: string
  participantsHeading: string
  participantsCompleted: (done: number, total: number) => string
  sessions: string
  untitled: string
  noDialogue: string
  leaning: string
  genderUnspecified: string
  attrs: {
    region: string
    occupation: string
    gender: string
    age: string
    income: string
    stance: string
    tags: string
    quirks: string
    bio: string
  }
  options: {
    gender: Record<string, string | undefined>
    income: Record<string, string | undefined>
    stance: Record<string, string | undefined>
  }
  sliderPoles: {
    calm: string
    anxious: string
    optimistic: string
    cynical: string
    frugal: string
    spendthrift: string
  }
  /** Localized CSV header labels (same column order as csvHeader). */
  csv: {
    personaId: string
    personaName: string
    locale: string
    runId: string
    turnIndex: string
    question: string
    answer: string
    questionTime: string
    answerTime: string
    questionIndex: string
  }
  /** Run-item status → localized label; unknown statuses print raw. */
  runItemStatus: Record<string, string>
  noTranscript: string
  noTranscriptError: (error: string) => string
}

/**
 * Slider axis (SLIDER_POLAR_LABELS key) → the low/high pole keys in
 * ReportLabels.sliderPoles. Same pairing as the slider UI's axes.
 */
const SLIDER_POLE_LABEL_KEYS: Record<
  keyof typeof SLIDER_POLAR_LABELS,
  [keyof ReportLabels['sliderPoles'], keyof ReportLabels['sliderPoles']]
> = {
  calm_anxious: ['calm', 'anxious'],
  optimistic_cynical: ['optimistic', 'cynical'],
  frugal_spendthrift: ['frugal', 'spendthrift'],
}

/** Canonical option key → localized label; unknown keys print raw values. */
function optionLabel(
  options: Record<string, string | undefined>,
  value: string,
): string {
  return options[value] ?? value
}

/**
 * Numbered Q/A block with locale-free `Q1.`/`A1.` labels; body text stays
 * raw (multi-line answers allowed). A blank line separates the question and
 * answer lines (and each pair from the next) so rendered markdown shows
 * them as distinct paragraphs, not one soft-wrapped block. A session with
 * turns but no dialogue (or none at all) renders the italic note instead of
 * an empty block.
 */
function qaMarkdownLines(
  turns: TranscriptTurn[],
  labels: ReportLabels,
): string[] {
  const pairs = qaPairsFromTurns(turns)
  if (pairs.length === 0) return [`_${labels.noDialogue}_`]
  const lines: string[] = []
  pairs.forEach((pair, i) => {
    const n = i + 1
    lines.push(`**Q${n}.** ${pair.question}`)
    lines.push('')
    lines.push(`**A${n}.** ${pair.answer}`)
    lines.push('')
  })
  return lines
}

/**
 * "## <participantProfile>" labeled lines; null/empty fields are omitted —
 * gender excepted, which falls back to the explicit "unspecified" label
 * (matching the persona profile page). Personality axes follow the
 * SLIDER_POLAR_LABELS convention shared with buildActiveRosterSummary: name
 * the pole the value leans toward (>= 50 → the high pole).
 */
function personaProfileLines(persona: Persona, labels: ReportLabels): string[] {
  const lines: string[] = [
    `- ${labels.attrs.region}: ${mdInline(persona.region)}`,
  ]
  if (persona.occupation)
    lines.push(`- ${labels.attrs.occupation}: ${mdInline(persona.occupation)}`)
  lines.push(
    `- ${labels.attrs.gender}: ${
      persona.gender
        ? mdInline(optionLabel(labels.options.gender, persona.gender))
        : labels.genderUnspecified
    }`,
  )
  if (persona.age !== null) lines.push(`- ${labels.attrs.age}: ${persona.age}`)
  if (persona.incomeBracket)
    lines.push(
      `- ${labels.attrs.income}: ${mdInline(
        optionLabel(labels.options.income, persona.incomeBracket),
      )}`,
    )
  if (persona.interviewStance)
    lines.push(
      `- ${labels.attrs.stance}: ${mdInline(
        optionLabel(labels.options.stance, persona.interviewStance),
      )}`,
    )
  if (persona.backgroundTags.length > 0) {
    lines.push(
      `- ${labels.attrs.tags}: ${mdInline(persona.backgroundTags.join(';'))}`,
    )
  }
  if (persona.quirksFreetext) {
    lines.push(`- ${labels.attrs.quirks}: ${mdInline(persona.quirksFreetext)}`)
  }
  for (const key of Object.keys(SLIDER_POLAR_LABELS) as Array<
    keyof typeof SLIDER_POLAR_LABELS
  >) {
    const value: number | undefined = persona.personalitySliders[key]
    if (value === undefined) continue
    const [low, high] = SLIDER_POLE_LABEL_KEYS[key]
    const lowPole = labels.sliderPoles[low]
    const highPole = labels.sliderPoles[high]
    const leaningPole = value >= 50 ? highPole : lowPole
    lines.push(
      `- ${lowPole} / ${highPole}: ${value} - ${labels.leaning} ${leaningPole}`,
    )
  }
  return lines
}

/**
 * Short profile brief for run reports: Region + Occupation (Region is NOT
 * NULL in the schema so it always renders), plus Age when `includeAge`.
 */
function personaBriefLines(
  persona: Persona,
  includeAge: boolean,
  labels: ReportLabels,
): string[] {
  const lines: string[] = [
    `- ${labels.attrs.region}: ${mdInline(persona.region)}`,
  ]
  if (persona.occupation)
    lines.push(`- ${labels.attrs.occupation}: ${mdInline(persona.occupation)}`)
  if (includeAge && persona.age !== null)
    lines.push(`- ${labels.attrs.age}: ${persona.age}`)
  return lines
}

function sessionHeading(
  transcript: Transcript,
  ordinal: number,
  labels: ReportLabels,
): string {
  return `### ${labels.sessionHeading(
    ordinal,
    mdInline(transcript.title?.trim() || labels.untitled),
    shortIso(transcript.createdAt.toISOString()),
  )}`
}

/**
 * Per-persona Markdown report: H1 + exported date + integrity blockquote,
 * Participant Profile, Bio, then one `Session <n>` block per transcript
 * (chronological input order). Provenance (system prompt, model snapshot)
 * is intentionally absent — it belongs to the JSON backup only.
 */
export function buildPersonaExportMarkdown(
  persona: Persona,
  transcripts: Transcript[],
  labels: ReportLabels,
): string {
  const lines: string[] = [
    `# ${labels.personaTitle(mdInline(persona.name))}`,
    '',
    labels.exportedLine(shortIso(new Date().toISOString())),
    '',
    `> ${labels.integrityLine}`,
    '',
    `## ${labels.participantProfile}`,
    '',
    ...personaProfileLines(persona, labels),
  ]
  if (persona.generatedBio?.trim()) {
    lines.push('', `## ${labels.attrs.bio}`, '', persona.generatedBio.trim())
  }
  if (transcripts.length > 0) {
    lines.push('', `## ${labels.sessions}`, '')
    transcripts.forEach((transcript, i) => {
      if (i > 0) lines.push('')
      lines.push(
        sessionHeading(transcript, i + 1, labels),
        '',
        ...qaMarkdownLines(transcript.turns, labels),
      )
    })
  }
  return lines.join('\n').trimEnd()
}

export type RunExportItem = {
  item: RunItem
  persona: Persona
  transcript: Transcript | null
}

/**
 * Per-run Markdown report: H1 + integrity blockquote, Overview (research
 * context + N-of-M completion), the numbered interview script, then one
 * participant section per run item. A run holds ONE group transcript per
 * persona — its Q/A renders directly under the participant heading, no
 * Session sub-heading. Items without a completed transcript say so instead
 * of silently rendering an empty participant (error-kind note kept).
 */
export function buildRunExportMarkdown(
  run: Run,
  items: RunExportItem[],
  script: string[],
  labels: ReportLabels,
): string {
  const lines: string[] = [
    `# ${labels.runTitle(shortIso(run.createdAt.toISOString()))}`,
    '',
    `> ${labels.integrityLine}`,
    '',
    `## ${labels.overview}`,
    '',
  ]
  if (run.researchContext?.trim()) {
    lines.push(`- ${labels.researchContext}: ${mdInline(run.researchContext)}`)
  }
  const doneCount = items.filter(({item}) => item.status === 'done').length
  lines.push(`- ${labels.participantsCompleted(doneCount, items.length)}`)
  lines.push('', `## ${labels.interviewScript}`, '')
  script.forEach((question, i) => {
    lines.push(`${i + 1}. ${mdInline(question)}`)
  })
  lines.push('', `## ${labels.participantsHeading}`, '')
  items.forEach(({item, persona, transcript}, i) => {
    if (i > 0) lines.push('')
    lines.push(
      `### ${mdInline(persona.name)} (${mdInline(
        labels.runItemStatus[item.status] ?? item.status,
      )})`,
      '',
    )
    if (!transcript || item.status !== 'done') {
      // run_items.error holds only a fixed short kind ('timeout',
      // 'persona missing', …): runNextStepAction stores err.kind and
      // never err.message, which can embed the LM Studio endpoint URL.
      // mdInline is defense-in-depth, keeping the note on one line even
      // if a legacy row carried a newline.
      lines.push(
        item.error
          ? `_${mdInline(labels.noTranscriptError(item.error))}_`
          : `_${labels.noTranscript}_`,
      )
      return
    }
    lines.push(
      ...personaBriefLines(persona, true, labels),
      '',
      ...qaMarkdownLines(transcript.turns, labels),
    )
  })
  return lines.join('\n').trimEnd()
}

/**
 * Per-session Markdown report: H1 + exported date + integrity, then the SAME
 * full persona profile + Bio sections as the persona report, followed by the
 * session's Q/A (no Session sub-heading — a lone session has no siblings).
 */
export function buildSessionExportMarkdown(
  persona: Persona,
  transcript: Transcript,
  labels: ReportLabels,
): string {
  const lines: string[] = [
    `# ${labels.sessionTitle(mdInline(persona.name))}`,
    '',
    labels.exportedLine(shortIso(new Date().toISOString())),
    '',
    `> ${labels.integrityLine}`,
    '',
    `## ${labels.participantProfile}`,
    '',
    ...personaProfileLines(persona, labels),
  ]
  if (persona.generatedBio?.trim()) {
    lines.push('', `## ${labels.attrs.bio}`, '', persona.generatedBio.trim())
  }
  lines.push('', ...qaMarkdownLines(transcript.turns, labels))
  return lines.join('\n').trimEnd()
}

/**
 * Wide comparison matrix for cross-persona analysis: one row per script
 * question (0-based index + verbatim question — same 0-based convention as
 * the long CSV's turn index; the two header cells are localized labels), one
 * column per participant in item order. The answer cell reads that persona's
 * transcript turn-pair at the same index — runNextStepAction appends script questions in order, so
 * pair i IS the answer to script question i. Participants without a
 * transcript (or whose transcript is shorter than the script) still get a
 * column; their cells stay empty, never fabricated.
 */
export function buildRunComparisonCsv(
  run: Run,
  items: RunExportItem[],
  labels: ReportLabels,
): string {
  const pairsByItem = items.map(({transcript}) =>
    transcript ? qaPairsFromTurns(transcript.turns) : null,
  )
  const rows: string[][] = [
    [
      labels.csv.questionIndex,
      labels.csv.question,
      ...items.map(({persona}) => persona.name),
    ],
  ]
  run.questionScript.forEach((question, index) => {
    rows.push([
      String(index),
      question,
      ...pairsByItem.map((pairs) => pairs?.[index]?.answer ?? ''),
    ])
  })
  return rows.map((row) => row.map(csvEscape).join(',')).join('\r\n')
}

