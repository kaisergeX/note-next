/** Verbatim research-integrity header line (pre-ship checklist item). */
// English source of truth. MD reports read ai.interview.export.integrityLine from dictionaries — keep en.json value in sync; JSON backups render this const.
export const EXPORT_INTEGRITY_LINE =
  'Simulated personas generated by an LLM for research purposes, not real people.'

export type QAPair = {
  /** Index within the FILTERED (system turns removed) user/assistant sequence. */
  turnIndex: number
  question: string
  answer: string
  questionTime: string | null
  answerTime: string | null
}

/**
 * Turns → numbered Q&A rows, mirroring the run detail page's
 * formatTranscriptTurns: system turns are bookkeeping, not dialogue. The
 * remaining user/assistant turns pair up consecutively; a trailing user turn
 * (question appended but the assistant turn never landed — offline/timeout)
 * yields a row with an empty answer, and a defensive unpaired assistant turn
 * (should not happen) a row with an empty question.
 *
 * The emitted turnIndex is positional within this filtered sequence. A
 * session with two consecutive user turns (e.g. a double submit) renders the
 * first as an empty-answer row: indices match the raw transcript, not the
 * chat UI's consecutive-turn dedupe. Pairing is kept data-faithful on
 * purpose.
 */
export function qaPairsFromTurns(turns: TranscriptTurn[]): QAPair[] {
  const dialogue = turns.filter((turn) => turn.role !== 'system')
  const pairs: QAPair[] = []
  for (let i = 0; i < dialogue.length; i++) {
    const turn = dialogue[i]!
    if (turn.role === 'user') {
      const next = dialogue[i + 1]
      if (next?.role === 'assistant') {
        pairs.push({
          turnIndex: i,
          question: turn.content,
          answer: next.content,
          questionTime: turn.timestamp,
          answerTime: next.timestamp,
        })
        i++
      } else {
        pairs.push({
          turnIndex: i,
          question: turn.content,
          answer: '',
          questionTime: turn.timestamp,
          answerTime: null,
        })
      }
    } else {
      pairs.push({
        turnIndex: i,
        question: '',
        answer: turn.content,
        questionTime: null,
        answerTime: turn.timestamp,
      })
    }
  }
  return pairs
}

/**
 * RFC 4180 field escaping plus CSV formula-injection mitigation: the value is
 * wrapped in double quotes only when needed (delimiter, quote, newline, or
 * leading/trailing whitespace — quoted fields survive Excel's whitespace
 * trimming) and embedded quotes are doubled. Conditional wrapping keeps rows
 * diffable; wrapping unconditionally is equally correct.
 *
 * A cell whose first character is `=`, `+`, `-`, `@`, tab or CR executes as a
 * formula in Excel, so such values are prefixed with a single quote (the
 * standard text-forcing mitigation) BEFORE the quoting logic — the quote
 * lands inside the cell. The schema's numeric columns (age, sliders 0–100)
 * are never negative, so no legitimate numeric cell starts with `-` and
 * gains a spurious quote.
 */
export function csvEscape(value: string): string {
  const guarded = /^[=+\-@\t\r]/.test(value) ? `'${value}` : value
  if (!/["\n\r,]/.test(guarded) && guarded === guarded.trim()) {
    return guarded
  }
  return `"${guarded.replaceAll('"', '""')}"`
}

/**
 * Stable server-side download-name slug: lowercase, diacritics stripped via
 * NFD decomposition (all Vietnamese tone marks live in U+0300–U+036F), every
 * non-alphanumeric run collapsed to '-'. The server doesn't know the UI
 * locale, so download names are stable-English-safe ASCII ("Trần Thị B" →
 * "tran-thi-b"); the UI note covers localized naming.
 */
export function asciiSlug(value: string): string {
  const slug = value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
  return slug.length > 0 ? slug : 'persona'
}

/**
 * Markdown inline-safe text: collapse whitespace runs (newlines included) to
 * single spaces and trim. Applied to every heading/label interpolation in the
 * markdown builders so a value containing a newline or a long space run
 * cannot split or corrupt the surrounding markdown block; a stray `#`
 * mid-heading is harmless once the value sits on one line.
 */
export function mdInline(value: string): string {
  return value.replaceAll(/\s+/g, ' ').trim()
}

function emptyWhenNull(value: string | null | undefined): string {
  return value ?? ''
}

/** The persona-level columns shared by every row of one transcript. */
function personaCsvBaseColumns(persona: Persona, runId: string): string[] {
  const sliders = persona.personalitySliders
  return [
    persona.id,
    persona.name,
    emptyWhenNull(persona.gender),
    persona.age === null ? '' : String(persona.age),
    persona.locale,
    persona.region,
    emptyWhenNull(persona.incomeBracket),
    emptyWhenNull(persona.occupation),
    persona.backgroundTags.join(';'),
    // Missing axes stay unset for pre-rework rows — never fabricated.
    String(sliders.calm_anxious ?? ''),
    String(sliders.optimistic_cynical ?? ''),
    String(sliders.frugal_spendthrift ?? ''),
    emptyWhenNull(persona.interviewStance),
    emptyWhenNull(persona.quirksFreetext),
    runId,
  ]
}

/**
 * Localized header row (label-driven, same column order as
 * personaCsvBaseColumns + the per-pair columns). Header count and row count
 * stay in lockstep: 14 persona-level cells + run_id + 5 pair cells = 20.
 */
function csvHeader(labels: ReportLabels): string[] {
  const poles = labels.sliderPoles
  return [
    labels.csv.personaId,
    labels.csv.personaName,
    labels.attrs.gender,
    labels.attrs.age,
    labels.csv.locale,
    labels.attrs.region,
    labels.attrs.income,
    labels.attrs.occupation,
    labels.attrs.tags,
    `${poles.calm} / ${poles.anxious}`,
    `${poles.optimistic} / ${poles.cynical}`,
    `${poles.frugal} / ${poles.spendthrift}`,
    labels.attrs.stance,
    labels.attrs.quirks,
    labels.csv.runId,
    labels.csv.turnIndex,
    labels.csv.question,
    labels.csv.answer,
    labels.csv.questionTime,
    labels.csv.answerTime,
  ]
}

function joinCsv(header: string[], rows: string[][]): string {
  return [header, ...rows]
    .map((row) => row.map(csvEscape).join(','))
    .join('\r\n')
}

function transcriptCsvRows(
  persona: Persona,
  transcript: Transcript,
  runId: string,
): string[][] {
  const base = personaCsvBaseColumns(persona, runId)
  return qaPairsFromTurns(transcript.turns).map((pair) => [
    ...base,
    String(pair.turnIndex),
    pair.question,
    pair.answer,
    pair.questionTime ?? '',
    pair.answerTime ?? '',
  ])
}

/** Per-persona CSV — run_id resolves per transcript (null for single sessions). */
export function buildPersonaExportCsv(
  persona: Persona,
  transcripts: Transcript[],
  labels: ReportLabels,
): string {
  const rows = transcripts.flatMap((transcript) =>
    transcriptCsvRows(persona, transcript, transcript.runId ?? ''),
  )
  return joinCsv(csvHeader(labels), rows)
}

/** Per-run CSV — a persona whose item never produced a transcript yields nothing. */
export function buildRunExportCsv(
  run: Run,
  items: RunExportItem[],
  labels: ReportLabels,
): string {
  const rows = items.flatMap(({persona, transcript}) =>
    transcript ? transcriptCsvRows(persona, transcript, run.id) : [],
  )
  return joinCsv(csvHeader(labels), rows)
}

/** Locale-free UTC stamp from a stored ISO string ("2026-09-27 10:02:03"). */
function shortIso(timestamp: string): string {
  return timestamp.replace('T', ' ').slice(0, 19)
}

