/**
 * Plain-object persona shape for the versioned JSON backups (no
 * InferSelectModel leak, no persona id — import mints a new ULID).
 * `systemPrompt` may be null (draft personas may not have one yet).
 */
export type PersonaJson = {
  name: string
  gender: string | null
  age: number | null
  locale: string
  region: string
  incomeBracket: string | null
  occupation: string | null
  backgroundTags: string[]
  personalitySliders: PersonalitySliders
  interviewStance: string | null
  quirksFreetext: string | null
  generatedBio: string | null
  systemPrompt: string | null
  status: PersonaStatus
  createdAt: string
  updatedAt: string
}

/** Transcript fields shared by every backup shape (id is the session ULID). */
export type TranscriptJson = {
  id: string
  title: string | null
  mode: TranscriptMode
  model: string
  /** Per-transcript snapshot — never null, unlike the persona-level prompt. */
  systemPrompt: string
  createdAt: string
  turns: TranscriptTurn[]
}

/**
 * Transcript base + its run link (if any). The runId is kept only in shapes
 * where the run context is present — the session backup and the run backup —
 * where it is informative rather than dangling; the persona backup emits
 * plain TranscriptJson sessions without it (see PersonaBackupJson).
 */
export type SessionJson = TranscriptJson & {runId: string | null}

function turnsToJson(turns: TranscriptTurn[]): TranscriptTurn[] {
  return turns.map((turn) => ({
    role: turn.role,
    content: turn.content,
    timestamp: turn.timestamp,
  }))
}

function transcriptBaseToJson(transcript: Transcript): TranscriptJson {
  return {
    id: transcript.id,
    title: transcript.title,
    mode: transcript.mode,
    model: transcript.model,
    systemPrompt: transcript.systemPrompt,
    createdAt: transcript.createdAt.toISOString(),
    turns: turnsToJson(transcript.turns),
  }
}

/** Shared internal mapper — keeps all three backup shapes consistent. */
function personaToJson(persona: Persona): PersonaJson {
  return {
    name: persona.name,
    gender: persona.gender,
    age: persona.age,
    locale: persona.locale,
    region: persona.region,
    incomeBracket: persona.incomeBracket,
    occupation: persona.occupation,
    backgroundTags: [...persona.backgroundTags],
    personalitySliders: {...persona.personalitySliders},
    interviewStance: persona.interviewStance,
    quirksFreetext: persona.quirksFreetext,
    generatedBio: persona.generatedBio,
    systemPrompt: persona.systemPrompt,
    status: persona.status,
    createdAt: persona.createdAt.toISOString(),
    updatedAt: persona.updatedAt.toISOString(),
  }
}

/** Shared internal mapper — keeps the session + run backup shapes consistent. */
function sessionToJson(transcript: Transcript): SessionJson {
  return {...transcriptBaseToJson(transcript), runId: transcript.runId}
}

export type PersonaBackupJson = {
  format: 'note-next.persona-backup'
  version: 1
  exportedAt: string
  integrity: string
  persona: PersonaJson
  /**
   * Plain sessions WITHOUT runId: the run itself is absent from this document
   * and import mints new ULIDs, so a carried-over runId would be a dangling
   * reference with nothing to resolve against.
   */
  sessions: TranscriptJson[]
}

export type RunBackupJson = {
  format: 'note-next.run-backup'
  version: 1
  exportedAt: string
  integrity: string
  run: {
    questionScript: string[]
    researchContext: string | null
    status: RunStatus
    createdAt: string
    updatedAt: string
  }
  participants: Array<{
    status: RunItemStatus
    error: string | null
    persona: PersonaJson
    /** SessionJson keeps runId — the run context is present in this document. */
    transcript: SessionJson | null
  }>
}

export type SessionBackupJson = {
  format: 'note-next.session-backup'
  version: 1
  exportedAt: string
  integrity: string
  persona: PersonaJson
  session: SessionJson
}

/** Versioned, import-ready persona backup: persona + every session (all modes). */
export function buildPersonaExportJson(
  persona: Persona,
  transcripts: Transcript[],
): string {
  const doc: PersonaBackupJson = {
    format: 'note-next.persona-backup',
    version: 1,
    exportedAt: new Date().toISOString(),
    integrity: EXPORT_INTEGRITY_LINE,
    persona: personaToJson(persona),
    // transcriptBaseToJson (no runId): the run is absent from this document
    // and import mints new ULIDs, so a runId would dangle.
    sessions: transcripts.map(transcriptBaseToJson),
  }
  return JSON.stringify(doc, null, 2)
}

/**
 * Versioned, import-ready run backup. `script` is the same array the MD
 * builder receives (the route passes run.questionScript) — kept as the
 * source of the run's questionScript so the MD/JSON builders stay symmetric.
 * Run + participant ids are dropped (import mints new ULIDs); the group
 * transcript's session id is kept as the stable key, and its runId is kept
 * too — the run context is present in this document, making it informative.
 */
export function buildRunExportJson(
  run: Run,
  items: RunExportItem[],
  script: string[],
): string {
  const doc: RunBackupJson = {
    format: 'note-next.run-backup',
    version: 1,
    exportedAt: new Date().toISOString(),
    integrity: EXPORT_INTEGRITY_LINE,
    run: {
      questionScript: script,
      researchContext: run.researchContext,
      status: run.status,
      createdAt: run.createdAt.toISOString(),
      updatedAt: run.updatedAt.toISOString(),
    },
    participants: items.map(({item, persona, transcript}) => ({
      status: item.status,
      error: item.error,
      persona: personaToJson(persona),
      transcript: transcript ? sessionToJson(transcript) : null,
    })),
  }
  return JSON.stringify(doc, null, 2)
}

/** Versioned, import-ready single-session backup: persona + one session. */
export function buildSessionExportJson(
  persona: Persona,
  transcript: Transcript,
): string {
  const doc: SessionBackupJson = {
    format: 'note-next.session-backup',
    version: 1,
    exportedAt: new Date().toISOString(),
    integrity: EXPORT_INTEGRITY_LINE,
    persona: personaToJson(persona),
    session: sessionToJson(transcript),
  }
  return JSON.stringify(doc, null, 2)
}
